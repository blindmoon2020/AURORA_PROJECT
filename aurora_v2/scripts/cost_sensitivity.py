#!/usr/bin/env python3
"""What the verified broker costs do to the result.

Institutional research confirmed that assumed 0.2 pip is optimistic: an IC Markets
Raw account pays ~0.1 pip average spread plus USD 3.50 per lot per side, which is
about 0.8 pip round trip on EURUSD; OANDA US quotes ~1.4 pip all-in. This reruns
the same walk-forward at three cost levels and writes the table.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from aurora.backtest.metrics import periods_per_year_for  # noqa: E402
from aurora.data import clean_candles, fetch_yahoo  # noqa: E402
from aurora.execution.paper import PaperBroker  # noqa: E402
from aurora.strategies import load_dna  # noqa: E402
from aurora.validation import run_walk_forward  # noqa: E402

GRID = {"fast": [8, 20], "slow": [50, 80], "stop_lookback": [5, 10], "rr": [2.0]}
SERIES = [("1h", "730d"), ("1d", "10y")]
COSTS = [(0.2, "assumed (old model)"), (0.8, "IC Markets Raw, spread+commission"),
         (1.4, "OANDA US, all-in")]


def main() -> int:
    dna = load_dna(ROOT / "strategies" / "ema_cross_eurusd.json")
    data = {}
    for interval, rng in SERIES:
        raw, _ = fetch_yahoo("EURUSD=X", interval, rng, cache_dir=ROOT / "data_cache")
        data[(interval, rng)] = clean_candles(raw)[0]

    rows = []
    for pips, label in COSTS:
        spread = pips * 0.0001
        for (interval, rng), candles in data.items():
            wf = run_walk_forward(
                candles, dna, GRID, n_folds=4, min_trades=2,
                broker_factory=lambda s=spread: PaperBroker(spread=s, slippage=0.00001),
            )
            m = wf.oos_metrics
            pf = m.profit_factor
            rows.append((pips, label, f"{interval}/{rng}", m.count,
                         "n/a" if pf is None else f"{pf:.2f}",
                         f"{m.net_pnl:+.2f}", f"{m.sharpe:.2f}",
                         f"{m.max_drawdown_pct:.2f}%"))

    out = ["# Cost sensitivity — what the verified spreads do to the result",
           "",
           "Generated by `scripts/cost_sensitivity.py`. Same strategy, same walk-forward,",
           "same folds; only the cost assumption changes. 0.2 pip was our placeholder;",
           "0.8 pip is an IC Markets Raw account (0.1 pip average spread plus USD 3.50 per lot",
           "per side); 1.4 pip is OANDA US all-in. Commission is folded into the spread",
           "equivalent, so no separate commission line is charged here.",
           "",
           "| spread (pip) | source | series | OOS trades | PF | net P&L | Sharpe | maxDD |",
           "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    out += ["",
            "Reading: costs are not a detail. If a premise survives 0.2 pip and dies at 0.8,",
            "it was a cost assumption, not an edge. This is the cheapest honesty test in the",
            "whole repository and it should be run before any parameter search."]
    path = ROOT / "docs" / "COST_SENSITIVITY.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out[-8:]))
    print(f"\nwrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
